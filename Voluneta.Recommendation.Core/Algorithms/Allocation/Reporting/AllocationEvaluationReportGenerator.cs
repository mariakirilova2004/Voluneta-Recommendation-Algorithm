using System.Globalization;
using System.Text;

namespace Voluneta.Recommendation.Core.Algorithms.Allocation.Reporting
{
    // Generates reproducible Algorithm 2 (priority allocation) evaluation artifacts: a single
    // CSV with one row per scenario/threshold/algorithm, and a Markdown report explaining the
    // methodology, results, and the cardinality-first behavior of Min-Cost Max-Flow. Reuses the
    // existing MinCostMaxFlowPriorityAllocator/GreedyPriorityAllocator via
    // AllocationEvaluationRunner and never changes either allocator.
    public static class AllocationEvaluationReportGenerator
    {
        public static (IReadOnlyList<AllocationScenario> Scenarios, IReadOnlyList<AllocationEvaluationRow> Rows) GenerateAndSave(string outputDirectory)
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(outputDirectory);

            var scenarios = AllocationEvaluationRunner.BuildScenarios();
            var rows = AllocationEvaluationRunner.Run(scenarios);

            Directory.CreateDirectory(outputDirectory);

            File.WriteAllText(Path.Combine(outputDirectory, "allocation_evaluation.csv"), BuildCsv(rows));
            File.WriteAllText(Path.Combine(outputDirectory, "allocation_evaluation_report.md"), BuildReport(scenarios, rows));

            return (scenarios, rows);
        }

        public static string BuildCsv(IReadOnlyList<AllocationEvaluationRow> rows)
        {
            var sb = new StringBuilder();
            sb.AppendLine("scenario,score_source,seed,threshold,volunteer_count,cause_count,total_capacity,algorithm,prioritized_count,total_score,average_selected_score,capacity_utilization");

            foreach (var row in rows)
            {
                sb.AppendLine(string.Join(",",
                    CsvEscape(row.ScenarioName),
                    CsvEscape(row.ScoreSource),
                    row.Seed.HasValue ? row.Seed.Value.ToString(CultureInfo.InvariantCulture) : string.Empty,
                    row.Threshold.ToString("F2", CultureInfo.InvariantCulture),
                    row.VolunteerCount.ToString(CultureInfo.InvariantCulture),
                    row.CauseCount.ToString(CultureInfo.InvariantCulture),
                    row.TotalCapacity.ToString(CultureInfo.InvariantCulture),
                    CsvEscape(row.AlgorithmName),
                    row.PrioritizedVolunteerCount.ToString(CultureInfo.InvariantCulture),
                    row.TotalCompatibilityScore.ToString("F6", CultureInfo.InvariantCulture),
                    row.AverageSelectedCompatibilityScore.ToString("F6", CultureInfo.InvariantCulture),
                    row.CapacityUtilization.ToString("F6", CultureInfo.InvariantCulture)));
            }

            return sb.ToString();
        }

        private static string BuildReport(IReadOnlyList<AllocationScenario> scenarios, IReadOnlyList<AllocationEvaluationRow> rows)
        {
            var sb = new StringBuilder();

            sb.AppendLine("# Allocation Algorithm Evaluation Report (Algorithm 2)");
            sb.AppendLine();
            sb.AppendLine($"Generated: {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC");
            sb.AppendLine();

            sb.AppendLine("## Configuration");
            sb.AppendLine();
            sb.AppendLine("- Algorithms compared: `MinCostMaxFlowPriorityAllocator` (existing optimal allocator) vs `GreedyPriorityAllocator` (existing baseline)");
            sb.AppendLine($"- Thresholds evaluated: {string.Join(", ", AllocationEvaluationRunner.Thresholds.Select(t => t.ToString("F2", CultureInfo.InvariantCulture)))}");
            sb.AppendLine("- Both algorithms are run on identical candidate pairs, compatibility scores, cause capacities, and thresholds for each scenario (fresh capacity instances per run).");
            sb.AppendLine("- Scenarios: 1 hand-authored educational case + 3 deterministic synthetic cases with varied volunteer/cause counts and capacities, generated from fixed random seeds.");
            sb.AppendLine();

            sb.AppendLine("## Important: constructed test data, not neural network predictions");
            sb.AppendLine();
            sb.AppendLine("All compatibility scores and capacities used in this evaluation are **constructed test fixtures**:");
            sb.AppendLine();
            sb.AppendLine("- The *Educational Greedy vs Optimal* scenario uses the same hand-authored scores as the Optimization demo's educational example (`DemoEducationalScenario`), deliberately chosen to make the Greedy vs Min-Cost Max-Flow trade-off easy to see.");
            sb.AppendLine("- The *Synthetic* scenarios use scores and capacities generated by `System.Random` with a fixed seed, so each run is reproducible but the scores do **not** come from the trained neural network and do not represent real volunteer/cause compatibility.");
            sb.AppendLine("- This report only evaluates allocation (Algorithm 2) behavior given some scores; it does not evaluate neural network prediction quality (see `neural_evaluation_report.md` for that).");
            sb.AppendLine();

            sb.AppendLine("## Methodology");
            sb.AppendLine();
            sb.AppendLine("For each scenario, the same candidate list and equivalent cause capacities are passed to both");
            sb.AppendLine("allocators at each threshold (0.30, 0.50, 0.70). Scenarios are built once with a fixed seed (where");
            sb.AppendLine("applicable) so results are fully reproducible across runs. For each algorithm/scenario/threshold");
            sb.AppendLine("combination, four metrics are recorded from the resulting `RecommendationPriorityResult`:");
            sb.AppendLine();
            sb.AppendLine("- **Prioritized volunteer count** - `PrioritizedCount`, the number of volunteers given a priority recommendation.");
            sb.AppendLine("- **Total compatibility score** - `TotalScore`, the sum of compatibility scores across all selected pairs.");
            sb.AppendLine("- **Average selected compatibility score** - total score divided by the prioritized count (0 when nothing is selected).");
            sb.AppendLine("- **Capacity utilization** - prioritized count divided by the scenario's total remaining capacity across all causes.");
            sb.AppendLine();

            sb.AppendLine("## Min-Cost Max-Flow vs Greedy: how to read the results");
            sb.AppendLine();
            sb.AppendLine("`MinCostMaxFlowPriorityAllocator` solves a min-cost max-flow problem: it first **maximizes the number");
            sb.AppendLine("of assignments** (flow), and only among solutions achieving that maximum assignment count does it");
            sb.AppendLine("minimize total cost (equivalently, maximize total compatibility for that cardinality). `GreedyPriorityAllocator`");
            sb.AppendLine("instead picks the best-scoring pairs first without this cardinality guarantee.");
            sb.AppendLine();
            sb.AppendLine("As a result, when both algorithms select the **same number** of volunteers, Min-Cost Max-Flow's total");
            sb.AppendLine("compatibility score is guaranteed to be greater than or equal to Greedy's for that scenario/threshold.");
            sb.AppendLine("However, **when the two algorithms select different numbers of volunteers**, their total scores are not");
            sb.AppendLine("directly comparable this way: Min-Cost Max-Flow may select more volunteers at a lower total or average");
            sb.AppendLine("score per volunteer, because it is optimizing assignment cardinality first. This report does not claim");
            sb.AppendLine("that Min-Cost Max-Flow's total compatibility must always exceed Greedy's; the measured counts and totals");
            sb.AppendLine("below should be read together, not the total score alone.");
            sb.AppendLine();

            sb.AppendLine("## Results");
            sb.AppendLine();

            foreach (var scenario in scenarios)
            {
                sb.AppendLine($"### {scenario.Name}");
                sb.AppendLine();
                sb.AppendLine($"- Score source: {scenario.ScoreSource}");
                if (scenario.Seed.HasValue)
                {
                    sb.AppendLine($"- Seed: {scenario.Seed.Value}");
                }
                sb.AppendLine($"- Volunteers: {scenario.VolunteerCount}, Causes: {scenario.CauseCount}, Total capacity: {scenario.TotalCapacity}");
                sb.AppendLine();
                sb.AppendLine("| Threshold | Algorithm | Prioritized Count | Total Score | Avg Selected Score | Capacity Utilization |");
                sb.AppendLine("|---|---|---|---|---|---|");

                foreach (var row in rows.Where(r => r.ScenarioName == scenario.Name))
                {
                    sb.AppendLine($"| {row.Threshold:F2} | {row.AlgorithmName} | {row.PrioritizedVolunteerCount} | {row.TotalCompatibilityScore:F4} | {row.AverageSelectedCompatibilityScore:F4} | {row.CapacityUtilization:F4} |");
                }

                sb.AppendLine();
            }

            sb.AppendLine("## Limitations");
            sb.AppendLine();
            sb.AppendLine("- Scores in all scenarios are constructed test fixtures (educational or seeded-random), not real neural network predictions or real volunteer/cause data.");
            sb.AppendLine("- Only 3 synthetic scenario sizes and 1 educational scenario are evaluated; results may not generalize to all candidate pool shapes.");
            sb.AppendLine("- Capacity utilization is defined relative to total capacity across causes, not per-cause utilization.");
            sb.AppendLine();

            return sb.ToString();
        }

        private static string CsvEscape(string value)
        {
            if (value.Contains(',') || value.Contains('"'))
            {
                return "\"" + value.Replace("\"", "\"\"") + "\"";
            }

            return value;
        }
    }
}
